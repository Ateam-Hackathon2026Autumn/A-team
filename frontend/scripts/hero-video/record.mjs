// Rebuild from the repository root (Node 20+, Playwright 1.64.x and its Chromium/ffmpeg installed):
//   mkdir -p /tmp/hero-video-work && npm install --prefix /tmp/hero-video-work playwright@1.64.1
//   PLAYWRIGHT_MODULE=/tmp/hero-video-work/node_modules/playwright \
//     node frontend/scripts/hero-video/record.mjs
// Optionally set CHROMIUM_EXECUTABLE and FFMPEG_EXECUTABLE to their local binary paths.
// If Chromium reports missing shared libraries, point LD_LIBRARY_PATH to their directory.
// No package.json or downloaded visual assets are used. Frames are deterministic JPEGs
// generated by Canvas and piped to the Playwright-bundled ffmpeg VP9 encoder.
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { once } from 'node:events';

const root=dirname(fileURLToPath(import.meta.url));
const output=resolve(root,'../../public/videos');
const require=createRequire(import.meta.url);
let chromium;
try { ({chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright')); }
catch { throw new Error('Set PLAYWRIGHT_MODULE to an installed Playwright package (see the header comment).'); }
const chromiumPath=process.env.CHROMIUM_EXECUTABLE || chromium.executablePath();
const ffmpegPath=process.env.FFMPEG_EXECUTABLE || join(dirname(dirname(chromiumPath)),'..','ffmpeg-1013','ffmpeg-linux');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:chromiumPath,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:720},deviceScaleFactor:1});
let encoder;
try {
  await page.goto(pathToFileURL(join(root,'index.html')).href,{waitUntil:'load'});
  await page.waitForFunction(()=>typeof window.renderHeroFrame==='function');
  const poster=await page.evaluate(()=>{window.renderHeroFrame(5);return document.querySelector('canvas').toDataURL('image/jpeg',.84).split(',')[1];});
  await writeFile(join(output,'home-hero-poster.jpg'),Buffer.from(poster,'base64'));
  encoder=spawn(ffmpegPath,['-hide_banner','-loglevel','error','-y','-f','image2pipe','-framerate','20','-vcodec','mjpeg','-i','pipe:0','-an','-c:v','libvpx-vp9','-b:v','0','-crf','34','-deadline','good','-cpu-used','4','-pix_fmt','yuv420p','-frames:v','400',join(output,'home-hero.webm')],{stdio:['pipe','ignore','pipe']});
  let error='';encoder.stderr.on('data',chunk=>error+=chunk);
  for(let frame=0;frame<400;frame++){
    const data=await page.evaluate(time=>{window.renderHeroFrame(time);return document.querySelector('canvas').toDataURL('image/jpeg',.88).split(',')[1];},frame/20);
    if(!encoder.stdin.write(Buffer.from(data,'base64')))await once(encoder.stdin,'drain');
    if(frame%100===0)process.stdout.write(`Rendered frame ${frame}/400\n`);
  }
  encoder.stdin.end();
  const [code]=await once(encoder,'close');
  if(code!==0)throw new Error(`ffmpeg exited ${code}: ${error}`);
  process.stdout.write(`Created ${join(output,'home-hero.webm')} and poster\n`);
} finally {await browser.close();if(encoder&&!encoder.killed)encoder.stdin.destroy();}
